"""
FoG Pseudo-Labeled Dataset - For semi-supervised training with pseudo-labels.

Loads unlabeled data from Zarr and assigns pseudo-labels from a pre-generated
prediction file. Supports confidence-based filtering and optional sample caps.
"""

import logging
from typing import List, Optional

import numpy as np
import torch

from data.config import PathsConfig
from data.dataset.config import DatasetConfig
from .base import BaseFOGDataset
from .schema import DatasetSample

logger = logging.getLogger(__name__)


class FOGPseudoLabeledDataset(BaseFOGDataset):
    """
    FoG dataset that assigns pseudo-labels to unlabeled data.

    Loads accelerometer data from an unlabeled Zarr store and pairs it with
    pseudo-labels from a prediction file generated by generate_pseudo_labels.py.

    Filters samples by confidence threshold and returns DatasetSample instances
    compatible with the classification pipeline.
    """

    def __init__(
        self,
        paths_cfg: PathsConfig,
        dataset_cfg: DatasetConfig,
        stage: str,
        patient_ids: Optional[List[str]] = None,
        pseudo_label_path: str = "",
        confidence_threshold: float = 0.9,
        max_samples: Optional[int] = None,
    ) -> None:
        """
        Initialize pseudo-labeled dataset.

        Args:
            paths_cfg: Path configuration pointing to unlabeled Zarr
            dataset_cfg: Dataset-specific configuration
            stage: Dataset stage (should be "train")
            patient_ids: Patient IDs to include (usually all unlabeled patients)
            pseudo_label_path: Path to .pt file with pseudo-labels
            confidence_threshold: Minimum confidence to include a sample (0-1).
                A sample is included if P(fog) >= threshold OR P(fog) <= (1-threshold).
            max_samples: Optional cap on number of pseudo-labeled samples
        """
        # Initialize base dataset (loads metadata, filters by patient_ids)
        super().__init__(paths_cfg, dataset_cfg, stage, patient_ids)

        # Load pseudo-labels
        if not pseudo_label_path:
            raise ValueError("pseudo_label_path is required for FOGPseudoLabeledDataset")

        pseudo_data = torch.load(pseudo_label_path, map_location="cpu", weights_only=False)
        pl_global_indices = pseudo_data["global_indices"]
        pl_probs = pseudo_data["fog_probability"]
        pl_labels = pseudo_data["predicted_label"]

        # Build lookup: global_idx -> (prob, label)
        pseudo_lookup = {}
        for i, gidx in enumerate(pl_global_indices):
            pseudo_lookup[int(gidx)] = (float(pl_probs[i]), int(pl_labels[i]))

        # Filter metadata_df to only samples that have pseudo-labels and pass confidence
        valid_indices = []
        self._pseudo_probs = []
        self._pseudo_labels = []

        for iloc_idx in range(len(self.metadata_df)):
            row = self.metadata_df.iloc[iloc_idx]
            global_idx = int(row.name)  # global_idx is the DataFrame index

            if global_idx not in pseudo_lookup:
                continue

            prob, label = pseudo_lookup[global_idx]
            confidence = max(prob, 1 - prob)

            if confidence >= confidence_threshold:
                valid_indices.append(iloc_idx)
                self._pseudo_probs.append(prob)
                self._pseudo_labels.append(label)

        # Apply filtering
        if valid_indices:
            self.metadata_df = self.metadata_df.iloc[valid_indices].copy()
        else:
            # Empty dataset - keep structure but with no rows
            self.metadata_df = self.metadata_df.iloc[:0].copy()

        self._pseudo_probs = np.array(self._pseudo_probs)
        self._pseudo_labels = np.array(self._pseudo_labels)

        # Apply max_samples cap with class balancing
        if max_samples is not None and len(self.metadata_df) > max_samples:
            rng = np.random.RandomState(42)
            fog_idx = np.where(self._pseudo_labels == 1)[0]
            nofog_idx = np.where(self._pseudo_labels == 0)[0]

            # 50/50 split, limited by the smaller class
            per_class = min(max_samples // 2, len(fog_idx), len(nofog_idx))
            if per_class == 0:
                # One class empty — fall back to random sampling
                keep_idx = rng.choice(len(self.metadata_df), max_samples, replace=False)
            else:
                fog_keep = rng.choice(fog_idx, per_class, replace=False)
                nofog_keep = rng.choice(nofog_idx, per_class, replace=False)
                keep_idx = np.concatenate([fog_keep, nofog_keep])

            keep_idx.sort()
            self.metadata_df = self.metadata_df.iloc[keep_idx].copy()
            self._pseudo_probs = self._pseudo_probs[keep_idx]
            self._pseudo_labels = self._pseudo_labels[keep_idx]

        # Update length
        self.length = len(self.metadata_df)

        # Log summary
        n_fog = int(self._pseudo_labels.sum()) if len(self._pseudo_labels) > 0 else 0
        n_no_fog = self.length - n_fog
        logger.info(
            f"Pseudo-labeled dataset: {self.length} samples "
            f"(threshold={confidence_threshold}, FOG={n_fog}, No-FOG={n_no_fog})"
        )

    def __getitem__(self, idx: int) -> DatasetSample:
        """
        Get pseudo-labeled sample.

        Returns DatasetSample compatible with classification pipeline.
        Pseudo-labels are broadcast to sequence length as uniform labels
        (entire patch gets the same label).
        """
        x, _labels, _patch_labels, valid_mask, metadata = self._get_raw_data(idx)

        # Use pseudo-label (broadcast to sequence length)
        pseudo_label = int(self._pseudo_labels[idx])
        seq_len = x.shape[-1]

        y = torch.full((seq_len,), pseudo_label, dtype=torch.long)
        patch_y = torch.tensor(pseudo_label, dtype=torch.long)
        valid_mask_tensor = torch.from_numpy(valid_mask).bool()

        # Mark as pseudo-labeled in metadata
        metadata["pseudo_labeled"] = True
        metadata["pseudo_confidence"] = float(self._pseudo_probs[idx])

        return DatasetSample(
            signal=x,
            metadata=metadata,
            labels=y,
            patch_label=patch_y,
            valid_mask=valid_mask_tensor,
        )

    def get_sampling_metadata(self) -> "pd.DataFrame":
        """Return metadata for balanced sampling with pseudo-labels."""
        import pandas as pd

        metadata = super().get_sampling_metadata()

        # Override class_label with pseudo-labels for balanced sampling
        if len(self._pseudo_labels) > 0:
            metadata = metadata.copy()
            metadata["class_label"] = self._pseudo_labels

        return metadata
